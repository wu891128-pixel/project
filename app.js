const pages=[...book.querySelectorAll('.page')];
const now=document.getElementById('pageNow');
const total=document.getElementById('pageTotal');
const prev=document.getElementById('prevPage');
const next=document.getElementById('nextPage');
let current=0;
total.textContent=String(pages.length);

function updateControls(){
  now.textContent=String(current+1);
  prev.disabled=current===0;
  next.disabled=current===pages.length-1;
}

function goTo(index){
  index=Math.max(0,Math.min(pages.length-1,index));
  current=index;
  pages[index].scrollIntoView({behavior:'smooth',block:'nearest',inline:'center'});
  updateControls();
}

prev.addEventListener('click',()=>goTo(current-1));
next.addEventListener('click',()=>goTo(current+1));

let scrollTimer;
book.addEventListener('scroll',()=>{
  clearTimeout(scrollTimer);
  scrollTimer=setTimeout(()=>{
    const center=book.scrollLeft+book.clientWidth/2;
    let best=0,bestDist=Infinity;
    pages.forEach((p,i)=>{
      const pCenter=p.offsetLeft+p.offsetWidth/2;
      const d=Math.abs(pCenter-center);
      if(d<bestDist){bestDist=d;best=i;}
    });
    current=best;
    updateControls();
  },80);
},{passive:true});

